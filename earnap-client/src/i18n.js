export function translateText(value) {
    return localizeValue(value);
}

function localizeValue(value) {
    if (activeLanguage !== 'bn') return value;
    const leading = String(value).match(/^\s*/)?.[0] || '';
    const trailing = String(value).match(/\s*$/)?.[0] || '';
    const core = String(value).trim();
    const exact = TRANSLATIONS.get(normalize(core));
    if (exact) return `${leading}${exact}${trailing}`;
    for (const [pattern, format] of DYNAMIC_PATTERNS) {
        if (pattern.test(core)) return `${leading}${core.replace(pattern, format)}${trailing}`;
    }
    return value;
}

function isUserContent(element) {
    return Boolean(element?.closest(USER_CONTENT_SELECTOR));
}

function localizeTextNode(node) {
    if (!node.parentElement || isUserContent(node.parentElement)) return;
    const current = node.nodeValue ?? '';
    const previousTarget = lastAppliedText.get(node);
    if (!originalText.has(node) || (previousTarget !== undefined && current !== previousTarget)) {
        originalText.set(node, current);
    }
    const target = localizeValue(originalText.get(node));
    lastAppliedText.set(node, target);
    if (target !== current) node.nodeValue = target;
}

function localizeAttribute(element, name) {
    if (!element.hasAttribute(name) || isUserContent(element)) return;
    let sources = originalAttributes.get(element);
    let targets = lastAppliedAttributes.get(element);
    if (!sources) {
        sources = new Map();
        originalAttributes.set(element, sources);
    }
    if (!targets) {
        targets = new Map();
        lastAppliedAttributes.set(element, targets);
    }
    const current = element.getAttribute(name) ?? '';
    const previousTarget = targets.get(name);
    if (!sources.has(name) || (previousTarget !== undefined && current !== previousTarget)) {
        sources.set(name, current);
    }
    const target = localizeValue(sources.get(name));
    targets.set(name, target);
    if (target !== current) element.setAttribute(name, target);
}

function localizeNode(node) {
    if (node.nodeType === Node.TEXT_NODE) {
        localizeTextNode(node);
        return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE || isUserContent(node)) return;
    ATTRIBUTE_NAMES.forEach(name => localizeAttribute(node, name));
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    let textNode;
    while ((textNode = walker.nextNode())) localizeTextNode(textNode);
    node.querySelectorAll('*').forEach(element => {
        if (isUserContent(element)) return;
        ATTRIBUTE_NAMES.forEach(name => localizeAttribute(element, name));
    });
}

function updateLanguageButtons() {
    document.querySelectorAll('[data-language-choice]').forEach(button => {
        const selected = button.dataset.languageChoice === activeLanguage;
        button.classList.toggle('is-active', selected);
        button.setAttribute('aria-pressed', String(selected));
    });
}

function wrapNativeDialogs() {
    if (dialogsWrapped || typeof window === 'undefined') return;
    try {
        const nativeAlert = window.alert.bind(window);
        const nativeConfirm = window.confirm.bind(window);
        const nativePrompt = window.prompt.bind(window);
        window.alert = message => nativeAlert(localizeValue(String(message ?? '')));
        window.confirm = message => nativeConfirm(localizeValue(String(message ?? '')));
        window.prompt = (message, defaultValue) => nativePrompt(
            localizeValue(String(message ?? '')),
            typeof defaultValue === 'string' ? localizeValue(defaultValue) : defaultValue,
        );
        dialogsWrapped = true;
    } catch {
        // Keep the app usable if the browser does not allow native dialog wrapping.
    }
}

export function setLanguage(language) {
    if (!['en', 'bn'].includes(language) || language === activeLanguage) return;
    activeLanguage = language;
    try {
        localStorage.setItem(STORAGE_KEY, language);
    } catch {
        // Keep the selection active for this page even when storage is blocked.
    }
    document.documentElement.lang = language;
    document.title = localizeValue('JMJob — Work. Earn. Grow.');
    updateLanguageButtons();
    localizeNode(document.body);
}

